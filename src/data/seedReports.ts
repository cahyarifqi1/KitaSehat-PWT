export function buildSimulatedReports(nowMs: number = Date.now()): EnvReport[] {
  return SEED_SPECS.map((spec) => {
    const kel = KELURAHAN_LIST.find((k) => k.id === spec.kelurahanId)!;
    const createdMs =
      nowMs - spec.daysAgo * 24 * 60 * 60 * 1000 - (spec.hoursOffset ?? 2) * 60 * 60 * 1000;
    const createdAt = new Date(createdMs).toISOString();

    const history: StatusHistoryItem[] = [
      {
        status: 'Baru',
        timestamp: createdAt,
        actor: spec.reporterName,
        note: 'Laporan dikirim oleh warga melalui BersihKita Purwokerto.',
      },
    ];

    let updatedAt = createdAt;

    if (spec.status === 'Diproses' || spec.status === 'Selesai') {
      const processMs = Math.min(nowMs - 30 * 60 * 1000, createdMs + 6 * 60 * 60 * 1000);
      const processIso = new Date(processMs).toISOString();
      updatedAt = processIso;
      history.push({
        status: 'Diproses',
        timestamp: processIso,
        actor: `Petugas Kel. ${kel.name}`,
        note:
          spec.status === 'Diproses' && spec.officerNote
            ? spec.officerNote
            : 'Laporan diverifikasi dan diteruskan ke regu lapangan kelurahan.',
      });
    }

    if (spec.status === 'Selesai') {
      const doneMs = Math.min(nowMs - 10 * 60 * 1000, createdMs + 22 * 60 * 60 * 1000);
      const doneIso = new Date(doneMs).toISOString();
      updatedAt = doneIso;
      history.push({
        status: 'Selesai',
        timestamp: doneIso,
        actor: `Petugas Kel. ${kel.name}`,
        note: spec.officerNote || 'Penanganan lapangan selesai dilakukan dan lokasi kembali bersih.',
      });
    }

    return {
      id: spec.id,
      issueType: spec.issueType,
      kelurahanId: kel.id,
      kelurahanName: kel.name,
      kecamatan: kel.kecamatan,
      addressNote: spec.addressNote,
      description: spec.description,
      severity: spec.severity,
      status: spec.status,
      lat: Number((kel.lat + spec.latOffset).toFixed(5)),
      lng: Number((kel.lng + spec.lngOffset).toFixed(5)),
      reporterName: spec.reporterName,
      photoUrl: spec.useSamplePhoto ? ISSUE_TYPE_META[spec.issueType].samplePhoto : undefined,
      createdAt,
      updatedAt,
      isSimulated: true,
      history,
    };
  }).sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
}

